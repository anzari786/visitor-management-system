import type {
   IdType,
   ManagedVisit,
   ManagedVisitor,
   VisitorAttendanceStatus,
} from '@/types/visit.types';

type VisitorSeed = {
   name: string;
   attendanceStatus?: VisitorAttendanceStatus;
   /** Schedule day this attendance belongs to (defaults to visit start date). */
   attendanceDate?: string;
   phone?: string;
   email?: string;
   organization?: string;
   idType?: IdType;
   idNumber?: string;
   checkedInAt?: string;
   assignedBadgeNumber?: string;
   assignedBadgeQr?: string;
};

function withIds(
   visitId: string,
   scheduleDate: string,
   entries: VisitorSeed[],
): ManagedVisitor[] {
   return entries.map((entry, index) => {
      const attendanceStatus = entry.attendanceStatus ?? 'pending';
      const day = entry.attendanceDate ?? scheduleDate;
      return {
         id: `${visitId}-v${index + 1}`,
         name: entry.name,
         attendanceStatus,
         phone: entry.phone,
         email: entry.email,
         organization: entry.organization,
         idType: entry.idType,
         idNumber: entry.idNumber,
         checkedInAt: entry.checkedInAt,
         assignedBadgeNumber: entry.assignedBadgeNumber,
         assignedBadgeQr: entry.assignedBadgeQr,
         attendanceByDate: {
            [day]: {
               date: day,
               status: attendanceStatus,
               checkedInAt: entry.checkedInAt,
            },
         },
      };
   });
}

